enum MediaPipelineError: Error, LocalizedError {
    case recordingNotWired
    case invalidRawRecordingSource
    case exportSessionUnavailable
    case exportFailed
    case exportCancelled
    case playbackPreparationInvalidated
    case plaintextProductionInvalidated
    case stagedPackageMissing
    case localPackageCollision(UUID)
    case invalidAuthenticatedThumbnailIdentifier
    case cryptoOperationFailed(String)

    var errorDescription: String? {
        switch self {
        case .recordingNotWired:
            return "The AVFoundation recording session has not been wired yet."
        case .invalidRawRecordingSource:
            return "The captured video is unavailable or is not a regular file. Record the video again."
        case .exportSessionUnavailable:
            return "AVFoundation could not create a video export session."
        case .exportFailed:
            return "The video export failed."
        case .exportCancelled:
            return "The video export was cancelled."
        case .playbackPreparationInvalidated:
            return "Playback preparation stopped because Kithra is no longer active."
        case .plaintextProductionInvalidated:
            return "Media preparation stopped because Kithra is no longer active."
        case .stagedPackageMissing:
            return "The staged media package is no longer available."
        case .localPackageCollision(let messageID):
            return "An encrypted local package already exists for message \(messageID.uuidString)."
        case .invalidAuthenticatedThumbnailIdentifier:
            return "The local thumbnail identifier is not bound to a valid authenticated envelope signature."
        case .cryptoOperationFailed(let operation):
            return "\(operation) failed."
        }
    }
}

struct PlaintextTemporaryFileCleanupError: Error, LocalizedError {
    let failedPaths: [String]

    var errorDescription: String? {
        "Kithra could not delete plaintext temporary media: \(failedPaths.joined(separator: ", "))."
    }
}

struct KithraPlaintextCleanupReport: Equatable {
    var removedFiles: [URL] = []
    var failedFiles: [URL] = []
    var activeFiles: [URL] = []
}

/// Removes only plaintext temporary artifacts whose names are generated by
/// Kithra. The allowlist is deliberately UUID-shaped and non-recursive so a
/// cleanup pass cannot remove another framework's temporary files or encrypted
/// message staging.
final class KithraPlaintextTempFileJanitor: @unchecked Sendable {
    static let shared = KithraPlaintextTempFileJanitor()

    private let lock = NSLock()
    private var retainedPaths: Set<String> = []
    private var producerCountsByPath: [String: Int] = [:]
    private var isClosedForAccountDeletion = false

    /// Reserves an exact plaintext output before any producer can create or
    /// write it. Closing the account-deletion barrier and reserving a path use
    /// the same lock, so a producer can never appear in the final-sweep gap.
    func preserveWhileInUse(_ url: URL) throws {
        lock.lock()
        guard !isClosedForAccountDeletion else {
            lock.unlock()
            throw MediaPipelineError.plaintextProductionInvalidated
        }
        retainedPaths.insert(canonicalPath(for: url))
        lock.unlock()
    }

    /// Registers destinations whose producer may still create or recreate the
    /// file. Retained ownership can be released by an early unlink, but this
    /// producer reservation survives until the definitive completion or
    /// cancellation callback calls `finishProducing`.
    func beginProducing(_ urls: [URL]) throws {
        let paths = urls.map(canonicalPath(for:))
        lock.lock()
        guard !isClosedForAccountDeletion else {
            lock.unlock()
            throw MediaPipelineError.plaintextProductionInvalidated
        }
        retainedPaths.formUnion(paths)
        for path in paths {
            producerCountsByPath[path, default: 0] += 1
        }
        lock.unlock()
    }

    func finishProducing(_ urls: [URL]) {
        let paths = urls.map(canonicalPath(for:))
        lock.lock()
        for path in paths {
            let remaining = (producerCountsByPath[path] ?? 0) - 1
            if remaining > 0 {
                producerCountsByPath[path] = remaining
            } else {
                producerCountsByPath[path] = nil
            }
        }
        lock.unlock()
    }

    func release(_ url: URL) {
        lock.lock()
        retainedPaths.remove(canonicalPath(for: url))
        lock.unlock()
    }

    func closeForAccountDeletion() {
        lock.lock()
        isClosedForAccountDeletion = true
        lock.unlock()
    }

    func reopenAfterAccountDeletionEnds() {
        lock.lock()
        isClosedForAccountDeletion = false
        lock.unlock()
    }

    var accountDeletionBarrierIsClosed: Bool {
        lock.lock()
        defer { lock.unlock() }
        return isClosedForAccountDeletion
    }

    static func ownsPlaintextFile(
        _ url: URL,
        applicationTemporaryRoot: URL,
        mediaTemporaryRoot: URL
    ) -> Bool {
        let canonicalURL = url.standardizedFileURL
        if ownsInlineRecordingFile(
            canonicalURL,
            applicationTemporaryRoot: applicationTemporaryRoot
        ) {
            return true
        }
        let parent = canonicalURL.deletingLastPathComponent()
        if parent == mediaTemporaryRoot.standardizedFileURL {
            return isMediaPlaintextFile(canonicalURL.lastPathComponent)
        }
        return false
    }

    static func ownsInlineRecordingFile(
        _ url: URL,
        applicationTemporaryRoot: URL
    ) -> Bool {
        let canonicalURL = url.standardizedFileURL
        return canonicalURL.deletingLastPathComponent()
            == applicationTemporaryRoot.standardizedFileURL
            && isInlineRecordingFile(canonicalURL.lastPathComponent)
    }

    @discardableResult
    func cleanupAbandonedFiles(
        fileManager: FileManager = .default,
        applicationTemporaryRoot: URL,
        mediaTemporaryRoot: URL
    ) -> KithraPlaintextCleanupReport {
        var report = KithraPlaintextCleanupReport()
        cleanupDirectChildren(
            of: applicationTemporaryRoot,
            fileManager: fileManager,
            matches: Self.isInlineRecordingFile,
            report: &report
        )
        cleanupDirectChildren(
            of: mediaTemporaryRoot,
            fileManager: fileManager,
            matches: Self.isMediaPlaintextFile,
            report: &report
        )
        // AVFoundation may have accepted a destination but not created it yet.
        // Include every owned reservation, even when no directory entry was
        // visible to either scan. Account deletion cannot proceed until its
        // definitive completion/cancellation path releases that reservation.
        lock.lock()
        let reservedURLs = retainedPaths.union(producerCountsByPath.keys)
            .map { URL(fileURLWithPath: $0) }
        lock.unlock()
        let reportedActivePaths = Set(report.activeFiles.map { canonicalPath(for: $0) })
        report.activeFiles.append(contentsOf: reservedURLs.filter { url in
            Self.ownsPlaintextFile(
                url,
                applicationTemporaryRoot: applicationTemporaryRoot,
                mediaTemporaryRoot: mediaTemporaryRoot
            ) && !reportedActivePaths.contains(canonicalPath(for: url))
        })
        return report
    }

    private func cleanupDirectChildren(
        of root: URL,
        fileManager: FileManager,
        matches: (String) -> Bool,
        report: inout KithraPlaintextCleanupReport
    ) {
        guard fileManager.fileExists(atPath: root.path) else {
            return
        }

        let children: [URL]
        do {
            children = try fileManager.contentsOfDirectory(
                at: root,
                includingPropertiesForKeys: [.isRegularFileKey, .isSymbolicLinkKey],
                options: [.skipsHiddenFiles]
            )
        } catch {
            report.failedFiles.append(root)
            return
        }

        for child in children where matches(child.lastPathComponent) {
            do {
                let values = try child.resourceValues(forKeys: [
                    .isRegularFileKey,
                    .isSymbolicLinkKey
                ])
                guard values.isRegularFile == true, values.isSymbolicLink != true else {
                    continue
                }
            } catch {
                report.failedFiles.append(child)
                continue
            }

            lock.lock()
            let childPath = canonicalPath(for: child)
            let isActive = retainedPaths.contains(childPath)
                || producerCountsByPath[childPath] != nil
            if isActive {
                report.activeFiles.append(child)
            } else {
                do {
                    try fileManager.removeItem(at: child)
                    report.removedFiles.append(child)
                } catch {
                    report.failedFiles.append(child)
                }
            }
            lock.unlock()
        }
    }

    private static func isInlineRecordingFile(_ name: String) -> Bool {
        matchesUUIDFile(name, prefix: "kithra-inline-merged-", extension: "mov")
            || matchesUUIDFile(name, prefix: "kithra-inline-", extension: "mov")
    }

    private static func isMediaPlaintextFile(_ name: String) -> Bool {
        matchesUUIDFile(name, prefix: "raw-", extension: "mov")
            || matchesUUIDFile(name, prefix: "delivery-", extension: "mp4")
            || matchesUUIDFile(name, prefix: "playback-", extension: "mp4")
            || matchesUUIDFile(name, prefix: "thumbnail-staged-", extension: "jpg")
            || matchesAuthenticatedThumbnailFile(name)
    }

    private static func matchesAuthenticatedThumbnailFile(_ name: String) -> Bool {
        let url = URL(fileURLWithPath: name)
        guard url.pathExtension == "jpg" else {
            return false
        }

        let stem = url.deletingPathExtension().lastPathComponent
        for prefix in ["thumb-outgoing-client-", "thumb-incoming-server-"] {
            guard stem.hasPrefix(prefix) else {
                continue
            }

            let remainder = String(stem.dropFirst(prefix.count))
            guard remainder.count == 36 + "-auth-".count + 128 else {
                continue
            }
            let identifierEnd = remainder.index(remainder.startIndex, offsetBy: 36)
            let identifier = String(remainder[..<identifierEnd])
            let authenticatedSuffix = remainder[identifierEnd...]
            guard UUID(uuidString: identifier) != nil,
                  authenticatedSuffix.hasPrefix("-auth-") else {
                continue
            }

            let signatureHex = authenticatedSuffix.dropFirst("-auth-".count)
            return signatureHex.unicodeScalars.allSatisfy { scalar in
                (scalar.value >= 48 && scalar.value <= 57)
                    || (scalar.value >= 97 && scalar.value <= 102)
            }
        }
        return false
    }

    private static func matchesUUIDFile(
        _ name: String,
        prefix: String,
        extension expectedExtension: String
    ) -> Bool {
        let url = URL(fileURLWithPath: name)
        guard url.pathExtension == expectedExtension else {
            return false
        }
        let stem = url.deletingPathExtension().lastPathComponent
        guard stem.hasPrefix(prefix) else {
            return false
        }
        let identifier = String(stem.dropFirst(prefix.count))
        return identifier.count == 36 && UUID(uuidString: identifier) != nil
    }

    private func canonicalPath(for url: URL) -> String {
        url.standardizedFileURL.path
    }
}

enum V1MediaLimits {
    static let maximumRecordingDurationSeconds: TimeInterval = 120
    static let maximumEncryptedBlobBytes: Int64 = 64 << 20
}

enum EncryptedMediaUploadPolicyError: Error, LocalizedError, Equatable {
    case invalidFile
    case emptyFile
    case declaredSizeMismatch(declared: Int, actual: Int64)
    case blobTooLarge(actual: Int64, maximum: Int64)

    var errorDescription: String? {
        switch self {
        case .invalidFile:
            return "The encrypted video file is unavailable or is not a regular file. Record the video again."
        case .emptyFile:
            return "The encrypted video file is empty. Record the video again."
        case .declaredSizeMismatch(let declared, let actual):
            return "The encrypted video changed before upload (expected \(declared) bytes, found \(actual)). Record the video again."
        case .blobTooLarge(let actual, let maximum):
            let actualMiB = Double(actual) / Double(1 << 20)
            let maximumMiB = Double(maximum) / Double(1 << 20)
            return String(
                format: "The encrypted video is %.1f MiB; Kithra V1 supports at most %.0f MiB. Record a shorter video or choose 480p.",
                actualMiB,
                maximumMiB
            )
        }
    }
}

enum EncryptedMediaUploadPolicy {
    @discardableResult
    static func validate(
        fileURL: URL,
        declaredBlobSize: Int,
        maximumBytes: Int64 = V1MediaLimits.maximumEncryptedBlobBytes
    ) throws -> Int64 {
        let values = try fileURL.resourceValues(forKeys: [
            .isRegularFileKey,
            .isSymbolicLinkKey,
            .fileSizeKey
        ])
        guard values.isRegularFile == true,
              values.isSymbolicLink != true,
              let fileSize = values.fileSize else {
            throw EncryptedMediaUploadPolicyError.invalidFile
        }

        let actualSize = Int64(fileSize)
        guard actualSize > 0 else {
            throw EncryptedMediaUploadPolicyError.emptyFile
        }
        guard actualSize == Int64(declaredBlobSize) else {
            throw EncryptedMediaUploadPolicyError.declaredSizeMismatch(
                declared: declaredBlobSize,
                actual: actualSize
            )
        }
        guard actualSize <= maximumBytes else {
            throw EncryptedMediaUploadPolicyError.blobTooLarge(
                actual: actualSize,
                maximum: maximumBytes
            )
        }
        return actualSize
    }
}

struct RecordingDurationBudget: Equatable {
    let maximumSeconds: TimeInterval
    private(set) var recordedSeconds: TimeInterval = 0

    init(maximumSeconds: TimeInterval = V1MediaLimits.maximumRecordingDurationSeconds) {
        self.maximumSeconds = maximumSeconds
    }

    var remainingSeconds: TimeInterval {
        max(0, maximumSeconds - recordedSeconds)
    }

    mutating func reset() {
        recordedSeconds = 0
    }

    mutating func includeSegment(durationSeconds: TimeInterval) {
        guard durationSeconds.isFinite, durationSeconds > 0 else {
            return
        }
        recordedSeconds = min(maximumSeconds, recordedSeconds + durationSeconds)
    }
}

