/// A narrowly scoped cross-thread handle for an exact plaintext output. The
/// wrapped janitor is lock protected and FileManager's per-call operations are
/// safe here; keeping this handle separate avoids treating the full media
/// pipeline (including key-management state) as Sendable.
private final class PlaintextOutputFileHandle: @unchecked Sendable {
    private let fileManager: FileManager
    private let plaintextTempJanitor: KithraPlaintextTempFileJanitor

    init(
        fileManager: FileManager,
        plaintextTempJanitor: KithraPlaintextTempFileJanitor
    ) {
        self.fileManager = fileManager
        self.plaintextTempJanitor = plaintextTempJanitor
    }

    func applyCompleteProtection(to url: URL) throws {
        try fileManager.setAttributes(
            [.protectionKey: FileProtectionType.complete],
            ofItemAtPath: url.path
        )
    }

    func remove(_ url: URL) {
        plaintextTempJanitor.release(url)
        if fileManager.fileExists(atPath: url.path) {
            try? fileManager.removeItem(at: url)
        }
    }
}
