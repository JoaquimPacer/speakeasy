/// A thread-safe, single-use authorization for producing plaintext while the
/// app is active. Output reservation and invalidation share one lock. Active AV
/// operations also register cancellation hooks so backgrounding both cancels
/// work and returns every exact output path for deterministic cleanup.
final class ForegroundPlaintextPermit: @unchecked Sendable {
    let id = UUID()

    private let lock = NSLock()
    private var valid = true
    private var outputURLsByPath: [String: URL] = [:]
    private var cancellationByOperationID: [UUID: @Sendable () -> Void] = [:]

    var isValid: Bool {
        lock.lock()
        defer { lock.unlock() }
        return valid
    }

    func registerOutput(_ url: URL) throws {
        try registerOutputs([url])
    }

    func registerOutputs(_ urls: [URL]) throws {
        lock.lock()
        defer { lock.unlock() }
        guard valid else {
            throw MediaPipelineError.plaintextProductionInvalidated
        }
        for url in urls {
            let canonicalURL = url.standardizedFileURL
            outputURLsByPath[canonicalURL.path] = canonicalURL
        }
    }

    func beginOperation(
        outputURLs: [URL],
        cancellation: @escaping @Sendable () -> Void
    ) throws -> UUID {
        lock.lock()
        defer { lock.unlock() }
        guard valid else {
            throw MediaPipelineError.plaintextProductionInvalidated
        }
        for url in outputURLs {
            let canonicalURL = url.standardizedFileURL
            outputURLsByPath[canonicalURL.path] = canonicalURL
        }
        let operationID = UUID()
        cancellationByOperationID[operationID] = cancellation
        return operationID
    }

    func finishOperation(_ operationID: UUID) {
        lock.lock()
        cancellationByOperationID[operationID] = nil
        lock.unlock()
    }

    /// Starts an already-registered producer while holding the same lock used
    /// by invalidation. Invalidation therefore either prevents the producer
    /// from starting or runs its cancellation hook after start returns; it can
    /// never cancel first and then allow AVFoundation work to start afterward.
    func startOperation(_ operationID: UUID, _ start: () -> Void) -> Bool {
        lock.lock()
        defer { lock.unlock() }
        guard valid, cancellationByOperationID[operationID] != nil else {
            return false
        }
        start()
        return true
    }

    func createOutput<T>(at url: URL, _ body: () throws -> T) throws -> T {
        try createOutputs(at: [url], body)
    }

    func createOutputs<T>(at urls: [URL], _ body: () throws -> T) throws -> T {
        lock.lock()
        defer { lock.unlock() }
        guard valid else {
            throw MediaPipelineError.plaintextProductionInvalidated
        }

        for url in urls {
            let canonicalURL = url.standardizedFileURL
            outputURLsByPath[canonicalURL.path] = canonicalURL
        }
        return try body()
    }

    func invalidate() -> [URL] {
        lock.lock()
        valid = false
        let cancellations = Array(cancellationByOperationID.values)
        cancellationByOperationID.removeAll()
        let outputURLs = Array(outputURLsByPath.values)
        lock.unlock()

        // AVFoundation cancellation callbacks can re-enter client code, so do
        // not invoke them while holding the permit lock.
        cancellations.forEach { $0() }
        return outputURLs
    }
}

typealias PlaybackPreparationPermit = ForegroundPlaintextPermit

/// Direction-specific storage namespaces keep a relay-selected server ID from
/// addressing an outgoing package that was created and named locally.
enum LocalEncryptedMediaIdentifier: Hashable {
    case outgoingClientMessage(UUID)
    case incomingServerMessage(UUID)
}

/// A thumbnail is addressed by its complete authenticated envelope signature,
/// not by a relay-selected server ID. The direction prefix also prevents an
/// incoming relay record from aliasing locally generated outgoing UI state.
struct AuthenticatedThumbnailIdentifier: Hashable {
    enum Authority: Hashable {
        case outgoingClientMessage(UUID)
        case incomingServerMessage(UUID)
    }

    let authority: Authority
    fileprivate let envelopeSignature: Data

    init(authority: Authority, envelopeSignature: Data) throws {
        guard envelopeSignature.count == 64 else {
            throw MediaPipelineError.invalidAuthenticatedThumbnailIdentifier
        }
        self.authority = authority
        self.envelopeSignature = envelopeSignature
    }
}

